async function repo(files: Record<string, string>) {
  const dir = await mkdtemp(join(tmpdir(), "lockwire-values-"));
  for (const [rel, content] of Object.entries(files)) {
    await mkdir(dirname(join(dir, rel)), { recursive: true });
    await writeFile(join(dir, rel), content, "utf8");
  }
  return dir;
}
const metrics = (lo: number, extra: Record<string, unknown> = {}) =>
  JSON.stringify({ ci: { canon: { cve: { lo, hi: 0.2412 } } }, model: "baseline-v2", ...extra });
const DOC = `# Results

<!-- lockwire results/metrics.json#ci.canon.cve.lo -->
The lower bound of the canonical CVE interval is 0.18.

<!-- lockwire paper/numbers.tex#ciCanonCVELo -->
The paper reports a lower bound of 0.18.
`;
const TEX = (v: string) => `\\newcommand{\\ciCanonCVELo}{${v}}\n`;

describe("value anchors end to end", () => {
  it("default to the `value` tier and record the value they were stamped against", async () => {
    const dir = await repo({ "results/metrics.json": metrics(0.1834), "paper/numbers.tex": TEX("0.18"), "CLAUDE.md": DOC });
    const linked = await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    expect(linked.created).toBe(2);
    const lock = JSON.parse(await readFile(join(dir, "lockwire.lock"), "utf8"));
    for (const a of lock.anchors) {
      expect(a.tiers).toEqual(["value"]);
      expect(a.fingerprints.value).toMatch(/^b3:/);
    }
    expect(lock.anchors.map((a: { value: string }) => a.value).sort()).toEqual(["0.18", "0.1834"]);
    expect((await check(dir, DEFAULT_CONFIG)).summary).toMatchObject({ anchors: 2, fresh: 2 });
  });

  it("a rerun that moves the value within the stated precision, or reorders the keys, is not drift", async () => {
    const dir = await repo({ "results/metrics.json": metrics(0.1834), "paper/numbers.tex": TEX("0.18"), "CLAUDE.md": DOC });
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    await writeFile(
      join(dir, "results/metrics.json"),
      `{\n  "model": "baseline-v2",\n  "ci": {"canon": {"cve": {"hi": 0.2412, "lo": 0.1791}}}\n}\n`,
      "utf8",
    );
    const { summary } = await check(dir, DEFAULT_CONFIG);
    expect(summary).toMatchObject({ fresh: 2, drifted: 0 });
    expect(summary.noise.singleHashWouldFlag).toBe(1); // a naive hash would have flagged it
  });

  it("the 0.18 -> 0.19 shift is flagged, says what moved, logs it, and fails the run", async () => {
    const dir = await repo({ "results/metrics.json": metrics(0.1834), "paper/numbers.tex": TEX("0.18"), "CLAUDE.md": DOC });
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    await writeFile(join(dir, "results/metrics.json"), metrics(0.1912), "utf8");
    await writeFile(join(dir, "paper/numbers.tex"), TEX("\\num{0.19}"), "utf8");
    const { results, summary } = await check(dir, DEFAULT_CONFIG);
    expect(summary.drifted).toBe(2);
    const json = results.find((r) => r.anchor.target.path.endsWith(".json"));
    expect(json?.value).toEqual({ was: "0.1834", now: "0.1912", claimed: ["0.18"], matches: false });
    expect(json?.driftedTiers).toEqual(["value"]);
    const events = (await readLedger(dir)).filter((e) => e.event === "anchor.drifted");
    expect(events.map((e) => e.note).sort()).toEqual(["0.18 -> 0.19", "0.1834 -> 0.1912"]);
    expect((await verifyLedger(dir)).ok).toBe(true);
  });

  it("fixing the sentence (and re-linking) clears it; restoring the value clears it on its own", async () => {
    const dir = await repo({ "results/metrics.json": metrics(0.1834), "paper/numbers.tex": TEX("0.18"), "CLAUDE.md": DOC });
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    await writeFile(join(dir, "results/metrics.json"), metrics(0.1912), "utf8");
    expect((await check(dir, DEFAULT_CONFIG)).summary.drifted).toBe(1);

    await writeFile(join(dir, "results/metrics.json"), metrics(0.1801), "utf8"); // back within 0.18
    expect((await check(dir, DEFAULT_CONFIG)).summary).toMatchObject({ drifted: 0, fresh: 2 });

    await writeFile(join(dir, "results/metrics.json"), metrics(0.1912), "utf8");
    await check(dir, DEFAULT_CONFIG);
    const doc = await readFile(join(dir, "CLAUDE.md"), "utf8");
    await writeFile(join(dir, "CLAUDE.md"), doc.replace("interval is 0.18.", "interval is 0.19."), "utf8");
    const relinked = await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor, { reviewed: true });
    expect(relinked.skipped).toEqual([]);
    expect((await check(dir, DEFAULT_CONFIG)).summary).toMatchObject({ drifted: 0, fresh: 2 });
  });

  it("an edited sentence that now states the wrong number is flagged as both a claim edit and a mismatch", async () => {
    const dir = await repo({ "results/metrics.json": metrics(0.1834), "paper/numbers.tex": TEX("0.18"), "CLAUDE.md": DOC });
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    const doc = await readFile(join(dir, "CLAUDE.md"), "utf8");
    await writeFile(join(dir, "CLAUDE.md"), doc.replace("interval is 0.18.", "interval is 0.21."), "utf8");
    const r = (await check(dir, DEFAULT_CONFIG)).results.find((x) => x.anchor.target.path.endsWith(".json"));
    expect(r?.status).toBe("drifted");
    expect(r?.claimChanged).toBe(true);
    expect(r?.value?.matches).toBe(false);
    expect(r?.value?.claimed).toEqual(["0.21"]);
  });

  it("`link` refuses to bind a sentence that already states the wrong value", async () => {
    const dir = await repo({
      "results/metrics.json": metrics(0.1912),
      "CLAUDE.md": "# R\n\n<!-- lockwire results/metrics.json#ci.canon.cve.lo -->\nThe lower bound is 0.18.\n",
    });
    const r = await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    expect(r.created).toBe(0);
    expect(r.skipped[0]?.reason).toBe(
      "the claim states 0.18 but results/metrics.json#ci.canon.cve.lo is 0.1912: fix the sentence, then link",
    );
    expect(await readFile(join(dir, "CLAUDE.md"), "utf8")).not.toContain("id="); // nothing stamped
  });

  it("a sentence with no number falls back to plain fingerprint drift", async () => {
    const dir = await repo({
      "results/metrics.json": metrics(0.1834),
      "CLAUDE.md": "# R\n\n<!-- lockwire results/metrics.json#ci.canon.cve.lo -->\nThe lower bound comes from the canonical run.\n",
    });
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    await writeFile(join(dir, "results/metrics.json"), metrics(0.1835), "utf8");
    const [r] = (await check(dir, DEFAULT_CONFIG)).results;
    expect(r?.status).toBe("drifted");
    expect(r?.value).toEqual({ was: "0.1834", now: "0.1835", claimed: [], matches: true });
  });

  it("a string value is checked by containment", async () => {
    const dir = await repo({
      "results/metrics.json": metrics(0.18),
      "CLAUDE.md": "# R\n\n<!-- lockwire results/metrics.json#model -->\nThe reference model is baseline-v2.\n",
    });
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    await writeFile(join(dir, "results/metrics.json"), metrics(0.18, { model: "baseline-v3" }), "utf8");
    const [r] = (await check(dir, DEFAULT_CONFIG)).results;
    expect(r?.status).toBe("drifted");
    expect(r?.value?.matches).toBe(false);
  });

  it("a key that disappears orphans the anchor; an unparseable data file orphans it without crashing", async () => {
    const dir = await repo({ "results/metrics.json": metrics(0.1834), "paper/numbers.tex": TEX("0.18"), "CLAUDE.md": DOC });
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    await writeFile(join(dir, "paper/numbers.tex"), "\\newcommand{\\somethingElse}{1}\n", "utf8");
    await writeFile(join(dir, "results/metrics.json"), "{ truncated", "utf8");
    const { summary } = await check(dir, DEFAULT_CONFIG);
    expect(summary.orphaned).toBe(2);
  });

  it("stacked markers check each bound of a range on its own", async () => {
    const dir = await repo({
      "results/metrics.json": metrics(0.1834),
      "CLAUDE.md":
        "# R\n\n<!-- lockwire results/metrics.json#ci.canon.cve.lo -->\n<!-- lockwire results/metrics.json#ci.canon.cve.hi -->\nThe interval is 0.18–0.24.\n",
    });
    expect((await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor)).created).toBe(2);
    await writeFile(
      join(dir, "results/metrics.json"),
      JSON.stringify({ ci: { canon: { cve: { lo: 0.1834, hi: 0.2712 } } }, model: "baseline-v2" }),
      "utf8",
    );
    const drifted = (await check(dir, DEFAULT_CONFIG)).results.filter((r) => r.status === "drifted");
    expect(drifted.map((r) => r.anchor.target.symbol)).toEqual(["ci.canon.cve.hi"]);
  });

  it("a key holding an object doesn't drift when a pipeline emits its keys in a different order", async () => {
    const dir = await repo({ "results/metrics.json": metrics(0.1834) });
    await writeFile(
      join(dir, "CLAUDE.md"),
      "# R\n\n<!-- lockwire results/metrics.json#ci.canon.cve -->\nThe canonical CVE interval is recorded per run.\n",
      "utf8",
    );
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    const reordered = `{"model":"baseline-v2","ci":{"canon":{"cve":{"hi":0.2412,"lo":0.1834}}}}`;
    await writeFile(join(dir, "results/metrics.json"), reordered, "utf8");
    expect((await check(dir, DEFAULT_CONFIG)).summary.drifted).toBe(0);
    await writeFile(join(dir, "results/metrics.json"), metrics(0.19), "utf8");
    expect((await check(dir, DEFAULT_CONFIG)).summary.drifted).toBe(1);
  });

  it("whole-file data anchors don't drift when a pipeline merely reorders the keys", async () => {
    const dir = await repo({ "results/metrics.json": metrics(0.1834) });
    await writeFile(join(dir, "CLAUDE.md"), "# R\n\n<!-- lockwire results/metrics.json -->\nAll metrics live in one file.\n", "utf8");
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    const shuffled = `{"model":"baseline-v2","ci":{"canon":{"cve":{"hi":0.2412,"lo":0.1834}}}}`;
    await writeFile(join(dir, "results/metrics.json"), shuffled, "utf8");
    expect((await check(dir, DEFAULT_CONFIG)).summary.drifted).toBe(0);
    await writeFile(join(dir, "results/metrics.json"), metrics(0.2), "utf8");
    expect((await check(dir, DEFAULT_CONFIG)).summary.drifted).toBe(1);
  });

  it("`ack` re-stamps the value but can't make a wrong sentence right", async () => {
    const dir = await repo({ "results/metrics.json": metrics(0.1834), "paper/numbers.tex": TEX("0.18"), "CLAUDE.md": DOC });
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    await writeFile(join(dir, "results/metrics.json"), metrics(0.1912), "utf8");
    const r = (await check(dir, DEFAULT_CONFIG)).results.find((x) => x.status === "drifted");
    const acked = await ack(dir, r!.anchor.id, "false-positive", undefined, actor, DEFAULT_CONFIG);
    expect(acked.value).toBe("0.1912");
    const again = (await check(dir, DEFAULT_CONFIG)).results.find((x) => x.anchor.id === r!.anchor.id);
    expect(again?.status).toBe("drifted"); // the sentence still says 0.18
    expect(again?.value?.matches).toBe(false);
  });

  it("anchors stamped before the value tier existed still check clean", async () => {
    const dir = await repo({ "src/a.ts": "export function alpha(x: number): number {\n  return x + 1;\n}\n" });
    await writeFile(join(dir, "CLAUDE.md"), "# A\n\n<!-- lockwire src/a.ts#alpha sig -->\nalpha adds one.\n", "utf8");
    await linkDoc(dir, "CLAUDE.md", DEFAULT_CONFIG, actor);
    const lockPath = join(dir, "lockwire.lock");
    const lock = JSON.parse(await readFile(lockPath, "utf8"));
    delete lock.anchors[0].fingerprints.value; // as written by an older version
    await writeFile(lockPath, JSON.stringify(lock), "utf8");
    const { summary } = await check(dir, DEFAULT_CONFIG);
    expect(summary).toMatchObject({ fresh: 1, drifted: 0 });
    expect(summary.noise.singleHashWouldFlag).toBe(0);
  });
});

