describe("resolveValue: JSON", () => {
  const json = JSON.stringify({
    ci: { canon: { cve: { lo: 0.1834, hi: 0.2412 } } },
    runs: [{ seed: 1, score: 0.9 }, { seed: 2, score: 0.91 }],
    "dotted.key": { x: 7 },
    model: "baseline-v2",
    flags: { on: true, none: null },
  });
  const get = (key: string) => resolveValue(json, "json", key);

  it("follows dotted paths, array indexes in either style, and JSON Pointer for keys with dots", () => {
    expect(get("ci.canon.cve.lo")).toMatchObject({ found: true, value: 0.1834, display: "0.1834" });
    expect(get("runs[1].score").value).toBe(0.91);
    expect(get("runs.0.seed").value).toBe(1);
    expect(get("/dotted.key/x").value).toBe(7);
    expect(get("model")).toMatchObject({ value: "baseline-v2", display: '"baseline-v2"' });
    expect(get("flags.on").value).toBe(true);
    expect(get("flags.none")).toMatchObject({ found: true, value: null });
  });

  it("reports a missing key as not found rather than throwing", () => {
    for (const k of ["ci.canon.cve.mid", "runs[5].score", "model.length", "nope", "runs.x"])
      expect(get(k).found, k).toBe(false);
  });

  it("doesn't walk into inherited properties", () => {
    expect(get("ci.constructor").found).toBe(false);
    expect(get("__proto__").found).toBe(false);
  });

  it("throws on a file that isn't JSON (the caller reports it)", () => {
    expect(() => resolveValue("{ nope", "json", "a")).toThrow();
  });
});

describe("resolveValue: LaTeX macros", () => {
  const tex = String.raw`% generated by analysis.py — do not edit
\newcommand{\ciCanonCVELo}{0.18}
\newcommand\ciCanonCVEHi{\num{0.24}}
\renewcommand{\nRuns}{3}
\providecommand{\accuracy}{91.2\%}
\def\latency{\SI{12.5}{ms}}
\newcommand{\modelName}{\texttt{baseline-v2}}
\newcommand{\nested}{{0.5}}
\newcommand{\withArg}[1]{#1 units}
\newcommand{\bigN}{12{,}345}
`;
  const get = (k: string) => resolveValue(tex, "tex", k).value;

  it("reads the common definition forms, with or without the backslash in the key", () => {
    expect(get("ciCanonCVELo")).toBe(0.18);
    expect(get("\\ciCanonCVELo")).toBe(0.18);
    expect(get("ciCanonCVEHi")).toBe(0.24); // \num{} unwrapped
    expect(get("nRuns")).toBe(3);
    expect(get("latency")).toBe(12.5); // \SI{}{} unwrapped
    expect(get("bigN")).toBe(12345); // {,} thousands separator
  });

  it("keeps a percentage as its number, and non-numeric bodies as strings", () => {
    expect(get("accuracy")).toBe(91.2);
    expect(get("modelName")).toBe("\\texttt{baseline-v2}");
    expect(get("withArg")).toBe("#1 units");
  });

  it("reports an undefined macro as not found", () => {
    expect(resolveValue(tex, "tex", "ciCanonCVEMid").found).toBe(false);
  });

  it("knows which files are data", () => {
    expect(dataFormatOf("results/m.json")).toBe("json");
    expect(dataFormatOf("paper/numbers.TEX")).toBe("tex");
    expect(dataFormatOf("src/a.ts")).toBeUndefined();
    expect(dataFormatOf("Makefile")).toBeUndefined();
  });
});

describe("whole-file data anchors ignore key order and line endings", () => {
  it("re-serialising JSON with its keys shuffled is not a change", () => {
    const a = wholeFileContent('{"a":1,"b":{"x":1,"y":2}}', "json");
    const b = wholeFileContent('{\n  "b": {"y": 2, "x": 1},\n  "a": 1\n}\n', "json");
    expect(a).toBe(b);
    expect(wholeFileContent('{"a":2,"b":{"x":1,"y":2}}', "json")).not.toBe(a);
  });

  it("a CRLF checkout of a .tex file is the same file", () => {
    expect(wholeFileContent("\\newcommand{\\a}{1}\r\n", "tex")).toBe(wholeFileContent("\\newcommand{\\a}{1}\n", "tex"));
  });
});

describe("claimNumbers", () => {
  const nums = (s: string) => claimNumbers(s).map((n) => [n.text, n.value, n.decimals, n.percent]);

  it("finds the numbers a sentence states, with their precision", () => {
    expect(nums("The interval is 0.18–0.24 across 3 runs.")).toEqual([
      ["0.18", 0.18, 2, false],
      ["0.24", 0.24, 2, false],
      ["3", 3, 0, false],
    ]);
    expect(nums("Accuracy reached 91.2% on 1,024 samples, a −0.5 shift.")).toEqual([
      ["91.2%", 91.2, 1, true],
      ["1,024", 1024, 0, false],
      ["−0.5", -0.5, 1, false], // the text is kept as written, the value is parsed
    ]);
    expect(nums("p < .05 and 2.5e-3 and 40 percent")).toEqual([
      [".05", 0.05, 2, false],
      ["2.5e-3", 0.0025, 4, false],
      ["40 percent", 40, 0, true],
    ]);
  });

  it("ignores digits inside words and identifiers", () => {
    expect(nums("Use v2 of the x86 build with h264 and sha256.")).toEqual([]);
    expect(nums("See `src/v2/api.ts` and baseline-v2.")).toEqual([]);
  });
});

describe("checkClaimAgainstValue", () => {
  const ok = (claim: string, value: unknown) => checkClaimAgainstValue(claim, value).matches;

  it("matches at the precision the sentence states, never more", () => {
    expect(ok("the lower bound is 0.18", 0.1834)).toBe(true);
    expect(ok("the lower bound is 0.18", 0.1791)).toBe(true);
    expect(ok("the lower bound is 0.18", 0.1912)).toBe(false); // the 0.18 -> 0.19 shift
    expect(ok("the lower bound is 0.183", 0.1834)).toBe(true);
    expect(ok("the lower bound is 0.183", 0.1791)).toBe(false); // more digits, stricter
    expect(ok("roughly 0.2", 0.1834)).toBe(true);
    expect(ok("we use 3 seeds", 3)).toBe(true);
    expect(ok("we use 3 seeds", 4)).toBe(false);
    expect(ok("we use 3 seeds", 3.4)).toBe(true); // stated as an integer
  });

  it("accepts a percentage for a fraction, and numbers stored as strings", () => {
    expect(ok("accuracy is 18%", 0.18)).toBe(true);
    expect(ok("accuracy is 18.3%", 0.1834)).toBe(true);
    expect(ok("accuracy is 18%", 0.25)).toBe(false);
    expect(ok("the lower bound is 0.18", "0.18")).toBe(true);
    expect(ok("1,024 samples", 1024)).toBe(true);
  });

  it("checks a string value by containment", () => {
    expect(ok("The reference model is baseline-v2.", "baseline-v2")).toBe(true);
    expect(ok("The reference model is baseline-v2.", "baseline-v3")).toBe(false);
  });

  it("can't check a sentence with no number, or a value prose can't state", () => {
    expect(checkClaimAgainstValue("the lower bound is reported in the paper", 0.18).checkable).toBe(false);
    expect(checkClaimAgainstValue("flag is on", true).checkable).toBe(false);
    expect(checkClaimAgainstValue("config is set", { a: 1 }).checkable).toBe(false);
    expect(checkClaimAgainstValue("nothing", null).checkable).toBe(false);
  });

  it("KNOWN LIMIT: any matching number in the sentence satisfies it", () => {
    // Bind one value per marker. A range sentence bound to its upper value passes on that value even
    // if the lower one is wrong; stack a second marker for the lower bound to check both.
    expect(ok("the interval is 0.18–0.24", 0.24)).toBe(true);
  });
});

